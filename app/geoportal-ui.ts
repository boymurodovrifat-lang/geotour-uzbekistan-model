// Permalink state is read once on load and written back with history.replaceState.
export type Permalink = {
  lang?: string;
  bg?: string;
  layers?: string[];
  region?: string;
  opacity?: number;
  theme?: string;
  view?: { lat: number; lng: number; z: number };
  pin?: { lat: number; lng: number };
  sel?: string;
  route?: string;
};
export function readPermalink(search: string): Permalink {
  const q = new URLSearchParams(search),
    out: Permalink = {};
  const lang = q.get('lang');
  if (lang) out.lang = lang;
  const bg = q.get('bg');
  if (bg) out.bg = bg;
  const layers = q.get('layers');
  if (layers !== null) out.layers = layers.split(',').filter(Boolean);
  const region = q.get('region');
  if (region) out.region = region;
  const op = Number(q.get('op'));
  if (q.get('op') && Number.isFinite(op)) out.opacity = Math.max(0, Math.min(100, op));
  const theme = q.get('theme');
  if (theme) out.theme = theme;
  const lat = Number(q.get('lat')),
    lng = Number(q.get('lng')),
    z = Number(q.get('z'));
  if (q.get('lat') && q.get('lng') && q.get('z') && [lat, lng, z].every(Number.isFinite)) out.view = { lat, lng, z };
  const pin = (q.get('pin') || '').split(',').map(Number);
  if (pin.length === 2 && pin.every(Number.isFinite) && Math.abs(pin[0]) <= 90 && Math.abs(pin[1]) <= 180) out.pin = { lat: pin[0], lng: pin[1] };
  const sel = q.get('sel');
  if (sel && /^[\w:.\-/]{1,80}$/.test(sel)) out.sel = sel;
  const route = q.get('route');
  if (route && /^[\w-]{1,60}$/.test(route)) out.route = route;
  return out;
}

